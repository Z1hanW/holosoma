export PHYSX_GPU_TOTAL_AGGREGATE_PAIRS_CAPACITY=${PHYSX_GPU_TOTAL_AGGREGATE_PAIRS_CAPACITY:-134217728}
export PHYSX_GPU_COLLISION_STACK_SIZE=${PHYSX_GPU_COLLISION_STACK_SIZE:-268435456}
EOF
}

check_node() {
  local node="$1"
  local cmd
  cmd=$(cat <<EOF
set -euo pipefail
cd $(quote "${REMOTE_REPO}")
$(remote_env_exports 0)
source ./scripts/gpu_launch_defaults.sh
test -d "\${OMOMO_DATA_DIR}"
test -f "\${OMOMO_OBJECT_MAP}"
test -d "\${AS_CONTACT_EXPORT_ROOT}/clips"
test -f "\${BOX_RESUME_CKPT}"
CHECK_ONLY=1 bash distill_as_button_solid.sh
EOF
)
  remote_run "${node}" "${cmd}"
}

launch_node() {
  local node="$1"
  local node_rank="$2"
  local log_file="${REMOTE_REPO}/${LOG_DIR}/node_${node_rank}_${node}.log"
  local train_cmd
  train_cmd=$(cat <<EOF
set -euo pipefail
cd $(quote "${REMOTE_REPO}")
mkdir -p $(quote "${REMOTE_REPO}/${LOG_DIR}")
$(remote_env_exports "${node_rank}")
source ./scripts/gpu_launch_defaults.sh
echo "[INFO][${node}] session=${SESSION} node_rank=${node_rank}/${NNODES} per_gpu_envs=${PER_GPU_ENVS} total_num_envs=${TOTAL_NUM_ENVS}"
echo "[INFO][${node}] bank=${BANK_NAME} contact_export=${CONTACT_EXPORT_NAME}"
echo "[INFO][${node}] master=${MASTER_ADDR}:${MASTER_PORT} log=${log_file}"
echo "[INFO][${node}] nccl_if=${NCCL_SOCKET_IFNAME} gloo_if=${GLOO_SOCKET_IFNAME} nccl_ib_disable=${NCCL_IB_DISABLE}"
echo "[INFO][${node}] nccl_lib_dir=${NCCL_LIB_DIR}"
exec bash distill_as_button_solid.sh 2>&1 | tee $(quote "${log_file}")
EOF
)
  local cmd
  cmd=$(cat <<EOF
set -euo pipefail
cd $(quote "${REMOTE_REPO}")
mkdir -p $(quote "${REMOTE_REPO}/${LOG_DIR}")
if tmux has-session -t $(quote "${SESSION}") 2>/dev/null; then
  if [[ $(quote "${RESTART}") == "1" ]]; then
    tmux kill-session -t $(quote "${SESSION}")
  else
    echo "[ERROR][${node}] tmux session already exists: ${SESSION}" >&2
    exit 1
  fi
fi
tmux new-session -d -s $(quote "${SESSION}") $(quote "${train_cmd}")
tmux display-message -p -t $(quote "${SESSION}") "[INFO][${node}] started #{session_name}"
EOF
)
  remote_run "${node}" "${cmd}"
}

status_node() {
  local node="$1"
  local cmd
  cmd=$(cat <<EOF
set -euo pipefail
cd $(quote "${REMOTE_REPO}")
echo "===== ${node} ====="
tmux has-session -t $(quote "${SESSION}") 2>/dev/null && tmux list-sessions | grep -F $(quote "${SESSION}") || echo "tmux:${SESSION}:not-running"
latest_log=\$(ls -1t logs/batch_meshphys/${SESSION}_*/node_*_${node}.log 2>/dev/null | head -1 || true)
if [[ -n "\${latest_log}" ]]; then
  echo "log=\${latest_log}"
  tail -50 "\${latest_log}"
fi
EOF
)
  remote_run "${node}" "${cmd}"
}

stop_node() {
  local node="$1"
  local cmd
  cmd=$(cat <<EOF
set -euo pipefail
if tmux has-session -t $(quote "${SESSION}") 2>/dev/null; then
  tmux kill-session -t $(quote "${SESSION}")
  echo "[INFO][${node}] stopped ${SESSION}"
else
  echo "[INFO][${node}] ${SESSION} not running"
fi
EOF
)
  remote_run "${node}" "${cmd}"
}

run_check() {
  local pids=()
  local failed=0
  for node in "${NODE_LIST[@]}"; do
    check_node "${node}" &
    pids+=("$!")
  done
  for pid in "${pids[@]}"; do
    if ! wait "${pid}"; then
      failed=1
    fi
  done
  if (( failed != 0 )); then
    echo "[ERROR] One or more nodes failed check." >&2
    exit 1
  fi
}

run_launch() {
  echo "[INFO] Launching ${NNODES} nodes x ${NPROC} GPUs, PER_GPU_ENVS=${PER_GPU_ENVS}, TOTAL_NUM_ENVS=${TOTAL_NUM_ENVS}"
  local rank=0
  for node in "${NODE_LIST[@]}"; do
    echo "[INFO] Launching ${node} node_rank=${rank}"
    launch_node "${node}" "${rank}"
    rank=$((rank + 1))
  done
}

case "${ACTION}" in
  check)
    run_check
    ;;
  launch)
    run_launch
    ;;
  status)
    for node in "${NODE_LIST[@]}"; do
      status_node "${node}" || true
    done
    ;;
  stop)
    for node in "${NODE_LIST[@]}"; do
      stop_node "${node}" || true
    done
    ;;
  *)
    usage >&2
    exit 2
    ;;
esac
