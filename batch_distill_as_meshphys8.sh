#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)
cd "${SCRIPT_DIR}"

DEFAULT_NODES=(
  10.99.1.134
  10.99.0.117
  10.99.0.18
  10.99.0.227
  10.99.0.116
  10.99.0.165
  10.99.0.239
  10.99.0.167
)

usage() {
  cat <<'EOF'
Usage:
  BANK_NAME=<rollout_bank> CONTACT_EXPORT_NAME=<export_name> bash batch_distill_as_meshphys8.sh launch
  BANK_NAME=<rollout_bank> CONTACT_EXPORT_NAME=<export_name> bash batch_distill_as_meshphys8.sh check
  bash batch_distill_as_meshphys8.sh status
  bash batch_distill_as_meshphys8.sh stop

Useful env:
  NODES="node0 node1 ..."      override node list
  REMOTE_REPO=/home/ubuntu/FAR/holosoma
  SESSION=distill_as_meshphys_64gpu
  RUN_STAMP=<stamp>
  BANK_NAME=<required rollout bank under data/ds_as_data>
  CONTACT_EXPORT_NAME=<required contact export dir in BANK_NAME>
  PER_GPU_ENVS=1536            8 nodes x 8 GPUs x 1536 = 98304 global envs
  MASTER_ADDR=<node0>          default first node
  MASTER_PORT=29679
  NCCL_SOCKET_IFNAME=enp135s0  network interface for NCCL
  GLOO_SOCKET_IFNAME=enp135s0  network interface for Gloo
  NCCL_IB_DISABLE=1            force TCP socket path on these nodes
  NCCL_LIB_DIR=<path>          prepend runtime NCCL library directory
  BOX_RESUME_CKPT=<local init checkpoint>
  RESTART=1
  DRY_RUN=1
EOF
}

ACTION=${1:-status}
case "${ACTION}" in
  -h|--help|help)
    usage
    exit 0
    ;;
esac

if [[ "${ACTION}" == "launch" || "${ACTION}" == "check" ]]; then
  cat >&2 <<'EOF'
[ERROR] batch_distill_as_meshphys8.sh launch/check is quarantined.
This legacy controller does not pin/export the distributed runtime identity,
uses mutable remote source trees, and can report a successful check before the
real provenance/startup path runs. Use batch_ne.sh, whose snapshot, ownership,
runtime-manifest, checkpoint, and cross-rank provenance contracts are enforced.
EOF
  exit 2
fi

if [[ -n "${NODES:-}" ]]; then
  # shellcheck disable=SC2206
  NODE_LIST=(${NODES})
else
  NODE_LIST=("${DEFAULT_NODES[@]}")
fi
if [[ "${#NODE_LIST[@]}" -lt 1 ]]; then
  echo "[ERROR] Empty node list." >&2
  exit 2
fi

REMOTE_REPO=${REMOTE_REPO:-/home/ubuntu/FAR/holosoma}
SESSION=${SESSION:-distill_as_meshphys_64gpu}
RUN_STAMP=${RUN_STAMP:-$(date -u +%Y%m%d_%H%M%S)}
BANK_NAME=${BANK_NAME:-}
CONTACT_EXPORT_NAME=${CONTACT_EXPORT_NAME:-}
SOLID_TARGET_BANK_NAME=${SOLID_TARGET_BANK_NAME:-${BANK_NAME:+${BANK_NAME}_distill_solid_box_bin_barrel_ball}}
PER_GPU_ENVS=${PER_GPU_ENVS:-1536}
CUDA_VISIBLE_DEVICES=${CUDA_VISIBLE_DEVICES:-0,1,2,3,4,5,6,7}
NPROC=${NPROC:-8}
NNODES=${NNODES:-${#NODE_LIST[@]}}
MASTER_ADDR=${MASTER_ADDR:-${NODE_LIST[0]}}
MASTER_PORT=${MASTER_PORT:-29679}
NCCL_SOCKET_IFNAME=${NCCL_SOCKET_IFNAME:-enp135s0}
GLOO_SOCKET_IFNAME=${GLOO_SOCKET_IFNAME:-${NCCL_SOCKET_IFNAME}}
NCCL_IB_DISABLE=${NCCL_IB_DISABLE:-1}
NCCL_DEBUG=${NCCL_DEBUG:-WARN}
TORCH_NCCL_ASYNC_ERROR_HANDLING=${TORCH_NCCL_ASYNC_ERROR_HANDLING:-1}
HOLOSOMA_DEBUG_HEARTBEAT=${HOLOSOMA_DEBUG_HEARTBEAT:-0}
NCCL_LIB_DIR=${NCCL_LIB_DIR:-/home/ubuntu/.holosoma_deps/miniconda3/envs/hssim/lib/python3.11/site-packages/nvidia/nccl/lib}
RESTART=${RESTART:-1}
DRY_RUN=${DRY_RUN:-0}
SSH_OPTS=${SSH_OPTS:-"-o BatchMode=yes -o StrictHostKeyChecking=accept-new -o ConnectTimeout=10"}
PYTHON_BIN=${PYTHON_BIN:-/home/ubuntu/.holosoma_deps/miniconda3/envs/hssim/bin/python3.11}
BOX_RESUME_CKPT=${BOX_RESUME_CKPT:-/home/ubuntu/.cache/holosoma/checkpoints/as_ch51_convex_pretrain_model_22000.pt}
RUN_NAME=${RUN_NAME:-g1_w_object_distill_as_button_solid_meshphys_rollout67000_64gpu_init_box}
TRAINING_NAME=${TRAINING_NAME:-g1_29dof_wbt_w_object_distill_as_button_solid_meshphys_rollout67000_64gpu_depth}
SCHEDULE_NAME=${SCHEDULE_NAME:-as_meshphys_rollout67000_sparse_root_ppo_first_contact_drop_button_solid}
SCHEDULE_NOTES=${SCHEDULE_NOTES:-64-GPU AS solid distillation from mesh-physics teacher rollout contacts. Object geometry and URDF inertia come from the mesh-physics bank; contact points are regenerated by the AS teacher rollout.}
NUM_LEARNING_ITERATIONS=${NUM_LEARNING_ITERATIONS:-40000}
SAVE_INTERVAL=${SAVE_INTERVAL:-500}

if [[ "${ACTION}" == "launch" || "${ACTION}" == "check" ]]; then
  if [[ -z "${BANK_NAME}" ]]; then
    echo "[ERROR] BANK_NAME is required for ${ACTION}." >&2
    exit 2
  fi
  if [[ -z "${CONTACT_EXPORT_NAME}" ]]; then
    echo "[ERROR] CONTACT_EXPORT_NAME is required for ${ACTION}." >&2
    exit 2
  fi
fi
if ! [[ "${PER_GPU_ENVS}" =~ ^[0-9]+$ ]] || (( PER_GPU_ENVS < 1 )); then
  echo "[ERROR] PER_GPU_ENVS must be a positive integer. Got: ${PER_GPU_ENVS}" >&2
  exit 2
fi
if ! [[ "${NNODES}" =~ ^[0-9]+$ ]] || (( NNODES != ${#NODE_LIST[@]} )); then
  echo "[ERROR] NNODES must equal node list length. Got NNODES=${NNODES}, nodes=${#NODE_LIST[@]}" >&2
  exit 2
fi

TOTAL_NUM_ENVS=$((PER_GPU_ENVS * NPROC * NNODES))
LOG_DIR="logs/batch_meshphys/${SESSION}_${RUN_STAMP}"

quote() {
  printf '%q' "$1"
}

remote_run() {
  local node="$1"
  local cmd="$2"
  if [[ "${DRY_RUN}" == "1" ]]; then
    printf '[DRY_RUN] ssh %s %s\n' "${node}" "${cmd}"
    return 0
  fi
  # shellcheck disable=SC2086
  ssh ${SSH_OPTS} "${node}" "${cmd}"
}

remote_env_exports() {
  local node_rank="$1"
  cat <<EOF
export CUDA_VISIBLE_DEVICES=$(quote "${CUDA_VISIBLE_DEVICES}")
export OMNI_KIT_ACCEPT_EULA=YES
export ACCEPT_EULA=Y
export PYTHON_BIN=$(quote "${PYTHON_BIN}")
export NPROC=$(quote "${NPROC}")
export NNODES=$(quote "${NNODES}")
export NODE_RANK=$(quote "${node_rank}")
export MASTER_ADDR=$(quote "${MASTER_ADDR}")
export MASTER_PORT=$(quote "${MASTER_PORT}")
export NCCL_SOCKET_IFNAME=$(quote "${NCCL_SOCKET_IFNAME}")
export GLOO_SOCKET_IFNAME=$(quote "${GLOO_SOCKET_IFNAME}")
export NCCL_IB_DISABLE=$(quote "${NCCL_IB_DISABLE}")
export NCCL_DEBUG=$(quote "${NCCL_DEBUG}")
export TORCH_NCCL_ASYNC_ERROR_HANDLING=$(quote "${TORCH_NCCL_ASYNC_ERROR_HANDLING}")
export HOLOSOMA_DEBUG_HEARTBEAT=$(quote "${HOLOSOMA_DEBUG_HEARTBEAT}")
export NCCL_LIB_DIR=$(quote "${NCCL_LIB_DIR}")
export LD_LIBRARY_PATH=$(quote "${NCCL_LIB_DIR}")\${LD_LIBRARY_PATH:+:\${LD_LIBRARY_PATH}}
export PER_GPU_ENVS=$(quote "${PER_GPU_ENVS}")
export AS_SUCCESS133_FINAL0P5=1
export AS_RANK_LOCAL_SHARDS=1
export AS_SUCCESS133_BANK_NAME=$(quote "${BANK_NAME}")
export CORL_SOLID80_BANK_NAME=$(quote "${BANK_NAME}")
export OMOMO_DATA_DIR=$(quote "${REMOTE_REPO}/data/ds_as_data/${BANK_NAME}")
export OMOMO_OBJECT_MAP=$(quote "${REMOTE_REPO}/data/ds_as_data/${BANK_NAME}/_clip_object_urdf_map.json")
export SOLID_CONTACT_EXPORT_NAME=$(quote "${CONTACT_EXPORT_NAME}")
export AS_CONTACT_EXPORT_ROOT=$(quote "${REMOTE_REPO}/data/ds_as_data/${BANK_NAME}/${CONTACT_EXPORT_NAME}")
export SOLID_TARGET_BANK_NAME=$(quote "${SOLID_TARGET_BANK_NAME}")
export RESUME_FROM_BOX=1
export BOX_RESUME_CKPT=$(quote "${BOX_RESUME_CKPT}")
export RESUME_FROM_BOX_CKPT=$(quote "${BOX_RESUME_CKPT}")
export POLICY_INIT_CKPT=$(quote "${BOX_RESUME_CKPT}")
export RUN_NAME=$(quote "${RUN_NAME}")
