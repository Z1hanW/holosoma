                    asset,
                    data_root,
                    f"{key} asset for clip {clip_id}",
                )
        merged_clips[clip_id] = rewritten
        clip_sources[clip_id] = npz_path

if len(merged_clips) != expected_total:
    fail(
        f"realdata union expected {expected_total} clips from AS_EXPECTED_TOTAL, "
        f"found {len(merged_clips)}"
    )

# Re-list each source after hashing so additions/removals during discovery fail
# before a generation directory is created.
for source_dir in source_dirs:
    current_ids = {path.stem for path in source_dir.glob("*.npz")}
    expected_ids = {clip_id for clip_id, path in clip_sources.items() if path.parent == source_dir}
    if current_ids != expected_ids:
        fail(f"realdata source clip set changed during validation: {source_dir}")

source_file_manifest = [
    public_record(source_records[path])
    for path in sorted(source_records, key=lambda item: item.relative_to(data_root).as_posix())
]
map_core = {
    "clips": {clip_id: merged_clips[clip_id] for clip_id in sorted(merged_clips)},
    "source_dirs": [path.relative_to(data_root).as_posix() for path in source_dirs],
    "source_counts": source_counts,
}
identity_payload = {
    "schema_version": GENERATION_SCHEMA_VERSION,
    "generator": GENERATOR,
    "map_core_sha256": sha256_bytes(canonical_json_bytes(map_core)),
    "source_files": source_file_manifest,
}
generation_id = sha256_bytes(canonical_json_bytes(identity_payload))
generation = generation_root / generation_id
map_payload = {
    **map_core,
    "generation": {
        "schema_version": GENERATION_SCHEMA_VERSION,
        "id": generation_id,
        "manifest": MANIFEST_NAME,
    },
    "notes": "Immutable content-addressed CoRL realdata union.",
}
map_output = json.dumps(map_payload, indent=2, sort_keys=True, allow_nan=False).encode("utf-8") + b"\n"

generation_files: list[dict[str, Any]] = []
for clip_id in sorted(clip_sources):
    record = source_records[clip_sources[clip_id]]
    generation_files.append(
        {"path": f"{clip_id}.npz", "size": record["size"], "sha256": record["sha256"]}
    )
for source, destination in sorted(asset_destinations.items(), key=lambda item: item[1].as_posix()):
    record = source_records[source]
    generation_files.append(
        {"path": destination.as_posix(), "size": record["size"], "sha256": record["sha256"]}
    )
generation_files.append(
    {
        "path": "_clip_object_urdf_map.json",
        "size": len(map_output),
        "sha256": sha256_bytes(map_output),
    }
)
manifest = {
    **identity_payload,
    "generation_id": generation_id,
    "clip_count": len(merged_clips),
    "source_counts": source_counts,
    "generation_files": generation_files,
}
manifest_output = json.dumps(manifest, indent=2, sort_keys=True, allow_nan=False).encode("utf-8") + b"\n"

reject_symlink_components(out_alias, data_root, "realdata union alias parent", include_leaf=False)
out_alias.parent.mkdir(parents=True, exist_ok=True)
generation_root.mkdir(parents=True, exist_ok=True)
reject_symlink_components(generation_root, data_root, "realdata generation root", include_leaf=True)
if generation_root.resolve(strict=True) != generation_root:
    fail(f"realdata generation root resolved through an unexpected alias: {generation_root}")

lock_path = generation_root / ".publish.lock"
if lock_path.is_symlink():
    fail(f"realdata publication lock must not be a symlink: {lock_path}")
lock_fd = os.open(
    lock_path,
    os.O_RDWR | os.O_CREAT | os.O_CLOEXEC | getattr(os, "O_NOFOLLOW", 0),
    0o600,
)
if not stat.S_ISREG(os.fstat(lock_fd).st_mode):
    os.close(lock_fd)
    fail(f"realdata publication lock must be a regular file: {lock_path}")
with os.fdopen(lock_fd, "a+b") as lock_handle:
    fcntl.flock(lock_handle.fileno(), fcntl.LOCK_EX)
    # A concurrent publisher may have switched this name while we hashed the
    # sources; revalidate before publication.
    validate_existing_alias(out_alias, generation_root)
    for source, record in source_records.items():
        validate_source_file_unchanged(source, record, f"authenticated source file {source}")
    if generation.exists():
        existing = validate_generation_structure(generation, generation_root)
        if existing != manifest:
            fail(f"existing generation manifest does not match its content address: {generation}")
        for expected in generation_files:
            candidate = generation / expected["path"]
            if candidate.is_symlink() or not candidate.is_file():
                fail(f"existing generation is incomplete: {candidate}")
            observed = stable_file_digest(
                candidate,
                generation,
                f"generated union file {expected['path']}",
            )
            if public_record(observed) != expected:
                fail(f"existing generation file failed content validation: {candidate}")
    else:
        staging = generation_root / f".{generation_id}.staging-{os.getpid()}-{uuid.uuid4().hex}"
        staging.mkdir(mode=0o700)
        try:
            for clip_id in sorted(clip_sources):
                source = clip_sources[clip_id]
                copy_verified(
                    source,
                    staging / f"{clip_id}.npz",
                    source_records[source],
                    data_root,
                    f"motion clip {clip_id}",
                )
            for source, destination in sorted(
                asset_destinations.items(), key=lambda item: item[1].as_posix()
            ):
                copy_verified(
                    source,
                    staging / destination,
                    source_records[source],
                    data_root,
                    f"object asset {source}",
                )
            write_durable(staging / "_clip_object_urdf_map.json", map_output)
            write_durable(staging / MANIFEST_NAME, manifest_output)
            write_durable(staging / MARKER_NAME, LEGACY_MARKER_TEXT.encode("utf-8"))
            make_tree_read_only(staging)
            fsync_directory(staging)
            os.replace(staging, generation)
            fsync_directory(generation_root)
        except BaseException:
            if staging.exists():
                os.chmod(staging, 0o700)
                for current_root, dirs, files in os.walk(staging):
                    for name in dirs:
                        os.chmod(Path(current_root) / name, 0o700)
                    for name in files:
                        os.chmod(Path(current_root) / name, 0o600)
                shutil.rmtree(staging)
            raise

    for source, record in source_records.items():
        validate_source_file_unchanged(source, record, f"authenticated source file {source}")
    publish_alias(out_alias, generation, generation_root)
    reject_symlink_components(
        contact_root,
        data_root,
        "REALDATA_CONTACT_EXPORT_ROOT",
        include_leaf=True,
    )
    contact_root.mkdir(parents=True, exist_ok=True)
    reject_symlink_components(
        contact_root,
        data_root,
        "REALDATA_CONTACT_EXPORT_ROOT",
        include_leaf=True,
    )
    if contact_root.resolve(strict=True) != contact_root:
        fail(f"REALDATA_CONTACT_EXPORT_ROOT resolved through an unexpected alias: {contact_root}")

print(
    f"[INFO] Prepared CoRL realdata union: {out_alias} -> {generation} "
    f"({len(merged_clips)} clips, generation={generation_id})"
)
