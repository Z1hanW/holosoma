GENERATOR = "corl_numbers/train_as_general_realdata.sh"
GENERATION_SCHEMA_VERSION = 2
MARKER_NAME = ".generated_by_train_as_general_realdata"
MANIFEST_NAME = "realdata_union_manifest.json"
LEGACY_MARKER_TEXT = f"generated by {GENERATOR}\n"
CHUNK_SIZE = 8 * 1024 * 1024


def fail(message: str) -> NoReturn:
    raise SystemExit(f"[ERROR] {message}")


def lexical_path(raw: str | Path) -> Path:
    return Path(os.path.abspath(os.path.expanduser(str(raw))))


def is_within(path: Path, root: Path, *, strict: bool = False) -> bool:
    if path == root:
        return not strict
    return root in path.parents


def require_owned_path(path: Path, root: Path, label: str, *, strict: bool = False) -> None:
    if not is_within(path, root, strict=strict):
        relation = "strictly under" if strict else "under"
        fail(
            f"{label} must be {relation} repo-local data/: {path}. "
            "Aliases to /nfs or any other external root are forbidden."
        )


def reject_symlink_components(
    path: Path,
    root: Path,
    label: str,
    *,
    include_leaf: bool,
) -> None:
    """Reject path aliases before resolving them.

    This is intentionally stricter than merely checking the final resolved
    path.  It prevents an in-repo component from being swapped into an alias
    that redirects a later write outside the owned data root.
    """

    require_owned_path(path, root, label)
    if root.is_symlink():
        fail(f"repo-local data root must not be a symlink: {root}")
    relative = path.relative_to(root)
    parts = relative.parts if include_leaf else relative.parts[:-1]
    current = root
    for part in parts:
        current = current / part
        if current.is_symlink():
            fail(f"{label} contains a forbidden symlink component: {current}")


def paths_overlap(left: Path, right: Path) -> bool:
    return left == right or left in right.parents or right in left.parents


def canonical_json_bytes(payload: Any) -> bytes:
    try:
        return json.dumps(
            payload,
            sort_keys=True,
            separators=(",", ":"),
            ensure_ascii=False,
            allow_nan=False,
        ).encode("utf-8")
    except (TypeError, ValueError) as exc:
        fail(f"metadata is not canonical JSON: {exc}")


def sha256_bytes(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def stable_file_digest(path: Path, data_root: Path, label: str) -> dict[str, Any]:
    reject_symlink_components(path, data_root, label, include_leaf=True)
    try:
        before = path.stat()
    except FileNotFoundError:
        fail(f"missing {label}: {path}")
    if not stat.S_ISREG(before.st_mode):
        fail(f"{label} must be a regular file: {path}")

    digest = hashlib.sha256()
    try:
        with path.open("rb") as handle:
            while chunk := handle.read(CHUNK_SIZE):
                digest.update(chunk)
    except OSError as exc:
        fail(f"could not read {label} {path}: {exc}")
    after = path.stat()
    signature = (
        before.st_dev,
        before.st_ino,
        before.st_size,
        before.st_mtime_ns,
        before.st_ctime_ns,
    )
    if signature != (
        after.st_dev,
        after.st_ino,
        after.st_size,
        after.st_mtime_ns,
        after.st_ctime_ns,
    ):
        fail(f"{label} changed while its content digest was computed: {path}")
    return {
        "path": path.relative_to(data_root).as_posix(),
        "size": before.st_size,
        "sha256": digest.hexdigest(),
        "_signature": signature,
    }


def stable_read_bytes(path: Path, data_root: Path, label: str) -> tuple[bytes, dict[str, Any]]:
    record = stable_file_digest(path, data_root, label)
    payload = path.read_bytes()
    if len(payload) != record["size"] or sha256_bytes(payload) != record["sha256"]:
        fail(f"{label} changed between validation reads: {path}")
    return payload, record


def public_record(record: dict[str, Any]) -> dict[str, Any]:
    return {key: record[key] for key in ("path", "size", "sha256")}


def validate_source_file_unchanged(path: Path, record: dict[str, Any], label: str) -> None:
    current = path.stat()
    current_signature = (
        current.st_dev,
        current.st_ino,
        current.st_size,
        current.st_mtime_ns,
        current.st_ctime_ns,
    )
    if current_signature != record["_signature"]:
        fail(f"{label} changed after its content digest was computed: {path}")


def copy_verified(
    source: Path,
    destination: Path,
    record: dict[str, Any],
    data_root: Path,
    label: str,
) -> None:
    reject_symlink_components(source, data_root, label, include_leaf=True)
    validate_source_file_unchanged(source, record, label)
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, destination, follow_symlinks=False)
    # The destination is below a private staging root rather than data_root, so
    # hash it directly and compare it with the already authenticated source.
    digest = hashlib.sha256()
    size = 0
    with destination.open("rb") as handle:
        while chunk := handle.read(CHUNK_SIZE):
            size += len(chunk)
            digest.update(chunk)
        os.fsync(handle.fileno())
    if size != record["size"] or digest.hexdigest() != record["sha256"]:
        fail(f"copied {label} does not match its source snapshot: {source}")
    validate_source_file_unchanged(source, record, label)
    os.chmod(destination, 0o444)


def write_durable(path: Path, payload: bytes, mode: int = 0o444) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("wb") as handle:
        handle.write(payload)
        handle.flush()
        os.fsync(handle.fileno())
    os.chmod(path, mode)


def fsync_directory(path: Path) -> None:
    descriptor = os.open(path, os.O_RDONLY | os.O_DIRECTORY)
    try:
        os.fsync(descriptor)
    finally:
        os.close(descriptor)


def make_tree_read_only(root: Path) -> None:
    for current_root, dirs, files in os.walk(root, topdown=False, followlinks=False):
        current = Path(current_root)
        for name in files:
            item = current / name
            if item.is_symlink():
                fail(f"generated union unexpectedly contains a symlink: {item}")
            os.chmod(item, 0o444)
        for name in dirs:
            item = current / name
            if item.is_symlink():
                fail(f"generated union unexpectedly contains a symlink: {item}")
            os.chmod(item, 0o555)
        os.chmod(current, 0o555)
        fsync_directory(current)


def load_clips(payload: bytes, map_path: Path) -> dict[str, dict[str, Any]]:
    try:
        decoded = json.loads(payload)
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        fail(f"invalid JSON object map {map_path}: {exc}")
    clips = decoded.get("clips", decoded) if isinstance(decoded, dict) else None
    if not isinstance(clips, dict) or not clips:
        fail(f"invalid or empty object map: {map_path}")
    normalized: dict[str, dict[str, Any]] = {}
    for raw_clip_id, entry in clips.items():
        clip_id = str(raw_clip_id).strip()
        if not clip_id or clip_id != raw_clip_id or "/" in clip_id or "\\" in clip_id:
            fail(f"invalid clip id in {map_path}: {raw_clip_id!r}")
        if not isinstance(entry, dict):
            fail(f"object-map entry for {clip_id} must be an object: {map_path}")
        normalized[clip_id] = dict(entry)
    return normalized


def resolve_asset(
    raw: Any,
    source_dir: Path,
    data_root: Path,
    label: str,
) -> Path:
    if not isinstance(raw, str) or not raw.strip():
        fail(f"{label} must be a non-empty path string")
    candidate = Path(raw).expanduser()
    if not candidate.is_absolute():
        candidate = source_dir / candidate
    candidate = lexical_path(candidate)
    require_owned_path(candidate, data_root, label, strict=True)
    reject_symlink_components(candidate, data_root, label, include_leaf=True)
    if not candidate.is_file():
        fail(f"missing {label}: {candidate}")
    return candidate


def validate_generation_structure(generation: Path, generation_root: Path) -> dict[str, Any]:
    if generation.is_symlink() or not generation.is_dir() or generation.parent != generation_root:
        fail(f"invalid realdata union generation path: {generation}")
    marker = generation / MARKER_NAME
    manifest_path = generation / MANIFEST_NAME
    if marker.is_symlink() or not marker.is_file():
        fail(f"realdata union generation is incomplete (missing marker): {generation}")
    if manifest_path.is_symlink() or not manifest_path.is_file():
        fail(f"realdata union generation is incomplete (missing manifest): {generation}")
    try:
        marker_text = marker.read_text(encoding="utf-8")
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        fail(f"invalid realdata union generation manifest {manifest_path}: {exc}")
    if marker_text != LEGACY_MARKER_TEXT:
        fail(f"realdata union generation has an invalid ownership marker: {generation}")
    if manifest.get("generator") != GENERATOR:
        fail(f"realdata union generation has an unexpected owner: {generation}")
    if manifest.get("schema_version") != GENERATION_SCHEMA_VERSION:
        fail(f"realdata union generation has an unsupported schema: {generation}")
    if manifest.get("generation_id") != generation.name:
        fail(f"realdata union generation id/path mismatch: {generation}")
    if len(generation.name) != 64 or any(char not in "0123456789abcdef" for char in generation.name):
        fail(f"invalid content-addressed generation name: {generation.name}")
    identity = {
        "schema_version": manifest.get("schema_version"),
        "generator": manifest.get("generator"),
        "map_core_sha256": manifest.get("map_core_sha256"),
        "source_files": manifest.get("source_files"),
    }
    if sha256_bytes(canonical_json_bytes(identity)) != generation.name:
        fail(f"realdata union generation manifest does not match its content address: {generation}")
    generation_files = manifest.get("generation_files")
    if not isinstance(generation_files, list) or not generation_files:
        fail(f"realdata union generation has no authenticated file inventory: {generation}")
    seen_paths: set[str] = set()
    for record in generation_files:
        if not isinstance(record, dict):
            fail(f"invalid generated-file record in {manifest_path}")
        raw_relative = record.get("path")
        if not isinstance(raw_relative, str) or not raw_relative:
            fail(f"invalid generated-file path in {manifest_path}: {raw_relative!r}")
        relative = Path(raw_relative)
        if relative.is_absolute() or ".." in relative.parts or relative.as_posix() != raw_relative:
            fail(f"unsafe generated-file path in {manifest_path}: {raw_relative!r}")
        if raw_relative in seen_paths:
            fail(f"duplicate generated-file path in {manifest_path}: {raw_relative}")
        seen_paths.add(raw_relative)
        candidate = generation / relative
        reject_symlink_components(
            candidate,
            generation,
            f"generated union file {raw_relative}",
            include_leaf=True,
        )
        if not candidate.is_file():
            fail(f"realdata union generation is incomplete: {candidate}")
        if not isinstance(record.get("size"), int) or record["size"] < 0:
            fail(f"invalid generated-file size in {manifest_path}: {raw_relative}")
        digest = record.get("sha256")
        if not isinstance(digest, str) or len(digest) != 64 or any(
            char not in "0123456789abcdef" for char in digest
        ):
            fail(f"invalid generated-file digest in {manifest_path}: {raw_relative}")
    if "_clip_object_urdf_map.json" not in seen_paths:
        fail(f"generated union inventory omits its object map: {manifest_path}")
    return manifest


def validate_existing_alias(alias: Path, generation_root: Path) -> str:
    if not os.path.lexists(alias):
        return "missing"
    if alias.is_symlink():
        try:
            target = alias.resolve(strict=True)
        except (OSError, RuntimeError) as exc:
            fail(f"realdata union alias is dangling or cyclic: {alias}: {exc}")
        if target.parent != generation_root:
            fail(
                f"realdata union alias escapes its owned generation root: {alias} -> {target}; "
                "aliases to /nfs or other roots are forbidden"
            )
        validate_generation_structure(target, generation_root)
        return "symlink"
    if alias.is_dir():
        marker = alias / MARKER_NAME
        object_map = alias / "_clip_object_urdf_map.json"
        if marker.is_symlink() or not marker.is_file() or object_map.is_symlink() or not object_map.is_file():
            fail(
                f"refusing to replace non-generated realdata union directory: {alias}. "
                "Choose an empty REALDATA_UNION_DIR."
            )
        try:
            marker_text = marker.read_text(encoding="utf-8")
            legacy_map = json.loads(object_map.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            fail(f"could not validate legacy generated union {alias}: {exc}")
        if (
            marker_text != LEGACY_MARKER_TEXT
            or not isinstance(legacy_map, dict)
            or legacy_map.get("notes")
            != "Generated symlink union for corl_numbers/train_as_general_realdata.sh."
        ):
            fail(f"refusing to replace unrecognized legacy union directory: {alias}")
        for child in alias.iterdir():
            if child.name in {MARKER_NAME, "_clip_object_urdf_map.json"}:
                continue
            if child.suffix == ".npz" and child.is_symlink():
                continue
            if child.name == "contact_export_from_retarget" and child.is_dir() and not any(
                child.iterdir()
            ):
                continue
            fail(
                f"legacy union contains non-view data that will not be deleted: {child}. "
                "Move it out of REALDATA_UNION_DIR and rerun."
            )
        return "legacy-directory"
    fail(f"REALDATA_UNION_DIR must be absent, a generated alias, or a legacy generated directory: {alias}")


def rename_exchange(left: Path, right: Path) -> None:
    libc = ctypes.CDLL(None, use_errno=True)
    renameat2 = getattr(libc, "renameat2", None)
    if renameat2 is None:
        fail(
            "atomic migration of the legacy realdata union requires Linux renameat2; "
            "remove the legacy generated directory explicitly and rerun"
        )
    renameat2.argtypes = [ctypes.c_int, ctypes.c_char_p, ctypes.c_int, ctypes.c_char_p, ctypes.c_uint]
    renameat2.restype = ctypes.c_int
    at_fdcwd = -100
    rename_exchange_flag = 2
    result = renameat2(
        at_fdcwd,
        os.fsencode(left),
        at_fdcwd,
        os.fsencode(right),
        rename_exchange_flag,
    )
    if result != 0:
        errno_value = ctypes.get_errno()
        fail(f"atomic legacy-union migration failed: {os.strerror(errno_value)}")


def publish_alias(alias: Path, generation: Path, generation_root: Path) -> None:
    state = validate_existing_alias(alias, generation_root)
    temporary = alias.parent / f".{alias.name}.publish-{os.getpid()}-{uuid.uuid4().hex}"
    relative_target = os.path.relpath(generation, alias.parent)
    os.symlink(relative_target, temporary, target_is_directory=True)
    try:
        if state in {"missing", "symlink"}:
            os.replace(temporary, alias)
        elif state == "legacy-directory":
            rename_exchange(temporary, alias)
            # After RENAME_EXCHANGE the old legacy directory is parked at the
            # private temporary path.  The public name already points at the
            # complete generation, so cleanup cannot expose a partial union.
            shutil.rmtree(temporary)
        else:  # pragma: no cover - exhaustive guard
            fail(f"unsupported alias state: {state}")
        fsync_directory(alias.parent)
    finally:
        if temporary.is_symlink():
            temporary.unlink()
        elif temporary.exists():
            fail(f"legacy generated union cleanup was incomplete: {temporary}")
    target = alias.resolve(strict=True)
    if target != generation:
        fail(f"atomic realdata union publication selected an unexpected target: {target}")


